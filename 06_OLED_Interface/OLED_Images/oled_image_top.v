IMAGE INTO OLED DISPLAY


`timescale 1ns / 1ps


module top_image_ssd1331(
    input clk,
    input rst,
    output sclk,
    output mosi,
    output cs,
    output dc,
    output res_n,
    output vccen,
    output pmoden
);
    // SPI and OLED init wiring
    wire spi_done;
    wire [7:0] spi_data;
    wire spi_start;
    wire init_done;
    wire sclk_int, mosi_int, cs_int, dc_init, res_n_init;
    assign sclk   = sclk_int;
    assign mosi   = mosi_int;
    assign cs     = cs_int;
    assign dc     = drawing ? draw_dc : dc_init;
    assign res_n  = res_n_init;
    assign vccen  = 1'b1;
    assign pmoden = 1'b1;

    // Drawing state
    reg [6:0] pixel_x = 0;
    reg [6:0] pixel_y = 0;
    reg [7:0] draw_spi_data;
    reg draw_spi_start = 0;
    reg draw_dc = 0;
    reg drawing = 0;
    reg [3:0] state = 0;
    wire [15:0] rgb_pixel;

    // Image ROM interface (full-screen 96x64)
    wire [12:0] img_addr = pixel_y * 96 + pixel_x;
    wire [15:0] img_rgb;
    image_rom imgrom(
        .addr(img_addr),
        .rgb(img_rgb)
    );

    assign rgb_pixel = img_rgb;

    // OLED init and SPI
    ssd1331_init oled_init (
        .clk(clk),
        .rst(rst),
        .spi_data(spi_data),
        .spi_start(spi_start),
        .spi_done(spi_done),
        .dc(dc_init),
        .res_n(res_n_init),
        .init_done(init_done)
    );

    spi_master spi (
        .clk(clk),
        .rst(rst),
        .data_in(drawing ? draw_spi_data : spi_data),
        .start(drawing ? draw_spi_start : spi_start),
        .sclk(sclk_int),
        .mosi(mosi_int),
        .cs(cs_int),
        .done(spi_done)
    );

    // Drawing FSM: handles RAM write after init
    always @(posedge clk or posedge rst) begin
        if (rst) begin
            state <= 0;
            drawing <= 0;
            draw_spi_start <= 0;
            pixel_x <= 0;
            pixel_y <= 0;
        end else if (init_done) begin
            case (state)
                // Set column address
                0: begin draw_spi_data <= 8'h15; draw_spi_start <= 1; draw_dc <= 0; drawing <= 1; state <= 1; end
                1: begin draw_spi_start <= 0; if (spi_done) begin draw_spi_data <= 8'd0; draw_spi_start <= 1; state <= 2; end end
                2: begin draw_spi_start <= 0; if (spi_done) begin draw_spi_data <= 8'd95; draw_spi_start <= 1; state <= 3; end end
                // Set row address
                3: begin draw_spi_start <= 0; if (spi_done) begin draw_spi_data <= 8'h75; draw_spi_start <= 1; state <= 4; end end
                4: begin draw_spi_start <= 0; if (spi_done) begin draw_spi_data <= 8'd0; draw_spi_start <= 1; state <= 5; end end
                5: begin draw_spi_start <= 0; if (spi_done) begin draw_spi_data <= 8'd63; draw_spi_start <= 1; state <= 6; end end
                // Start sending pixel data
                6: begin draw_spi_start <= 0; if (spi_done) begin draw_dc <= 1; pixel_x <= 0; pixel_y <= 0; state <= 7; end end
                // Send high byte
                7: begin draw_spi_data <= rgb_pixel[15:8]; draw_spi_start <= 1; state <= 8; end
                // Send low byte, then update pixel coords
                8: begin
                    draw_spi_start <= 0;
                    if (spi_done) begin
                        draw_spi_data <= rgb_pixel[7:0]; draw_spi_start <= 1; state <= 9;
                    end
                end
                9: begin
                    draw_spi_start <= 0;
                    if (spi_done) begin
                        if (pixel_x < 95) pixel_x <= pixel_x + 1;
                        else begin
                            pixel_x <= 0;
                            if (pixel_y < 63) pixel_y <= pixel_y + 1;
                            else begin
                                pixel_y <= 0;
                                state <= 10; // Done
                            end
                        end
                        if (state != 10) state <= 7;
                    end
                end
                10: state <= 10;
                default: state <= 0;
            endcase
        end
   end
endmodule

